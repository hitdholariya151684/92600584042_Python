# Different Data Types

a = 10          # Integer
b = 5.5         # Float
c = "Hello"     # String
d = True        # Boolean

print("Integer:", a)
print("Float:", b)
print("String:", c)
print("Boolean:", d)

# Type Casting

print("\nType Casting:")

e = float(a)      # int to float
f = int(b)        # float to int
g = str(a)        # int to string

print("Int to Float:", e)
print("Float to Int:", f)
print("Int to String:", g)
